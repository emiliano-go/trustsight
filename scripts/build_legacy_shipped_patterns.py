"""Generate the shipped-pattern history that ``sync-rules --update`` repairs.

A hand-maintained ``LEGACY_RULE_PATTERNS`` keeps missing releases: a pattern
TrustSight shipped two versions ago is not an edit, but the tool cannot tell
unless it is listed.  This script reads ``DEFAULT_RULES`` from every tag and
records every pattern each current rule shipped with, so a stale install is
recognised no matter which release wrote it.

Usage:
    python scripts/build_legacy_shipped_patterns.py         # rewrite
    python scripts/build_legacy_shipped_patterns.py --check # fail if stale
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "trustsight" / "config" / "_legacy_shipped_patterns.py"

_EXECUTOR = "src/trustsight/config/_defaults_executor.py"
_RULES = "src/trustsight/config/_default_rules.py"
_LEGACY_CONFIG = "src/trustsight/config.py"


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout


def _files(ref: str) -> set[str]:
    return set(_git("ls-tree", "-r", "--name-only", ref).split())


def _blob(ref: str, path: str) -> str:
    return _git("show", f"{ref}:{path}")


def _rules_at(ref: str) -> dict[str, str] | None:
    """The shipped rule patterns at *ref*, or None when there is no config."""
    names = _files(ref)
    namespace: dict = {
        # The config modules touch ``__name__`` while importing.
        "__name__": "trustsight.config",
        "__package__": "trustsight.config",
    }
    try:
        if _RULES in names:
            exec(compile(_blob(ref, _EXECUTOR), _EXECUTOR, "exec"), namespace)
            exec(compile(_blob(ref, _RULES), _RULES, "exec"), namespace)
        elif _LEGACY_CONFIG in names:
            source = _blob(ref, _LEGACY_CONFIG)
            # Pre-package versions imported the stdlib tomllib shim
            # relatively; the extracted text cannot resolve that package.
            source = source.replace(
                "from ._toml import tomllib", "import tomllib")
            exec(compile(source, _LEGACY_CONFIG, "exec"), namespace)
        else:
            return None
    except Exception as exc:  # noqa: BLE001 - a broken old tag is skipped
        print(f"skipping {ref}: {type(exc).__name__}: {exc}", file=sys.stderr)
        return None

    rules = tomllib.loads(namespace["DEFAULT_RULES"]).get("rules", [])
    return {
        str(rule["id"]): str(rule["pattern"])
        for rule in rules
        if isinstance(rule.get("id"), str) and isinstance(rule.get("pattern"), str)
    }


def collect() -> dict[str, set[str]]:
    """Every superseded pattern for every rule the current build ships."""
    warnings.simplefilter("ignore", SyntaxWarning)
    current = _rules_at("HEAD")
    if current is None:
        raise SystemExit("no DEFAULT_RULES at HEAD")

    historical: dict[str, set[str]] = {}
    for tag in _git("tag", "--sort=v:refname").split():
        rules = _rules_at(tag)
        if not rules:
            continue
        for rule_id, pattern in rules.items():
            if rule_id not in current or pattern == current[rule_id]:
                continue
            historical.setdefault(rule_id, set()).add(pattern)
    return historical


def render(historical: dict[str, set[str]]) -> str:
    lines = [
        '"""Generated by scripts/build_legacy_shipped_patterns.py; do not edit.',
        "",
        "Every pattern an earlier release shipped for a rule this build still",
        "ships.  ``config sync-rules --update`` treats one of these on disk as",
        "superseded rather than as an operator edit.  Regenerate after changing",
        'a shipped pattern."""',
        "",
        "HISTORICAL_RULE_PATTERNS: dict[str, frozenset[str]] = {",
    ]
    for rule_id in sorted(historical):
        patterns = sorted(historical[rule_id])
        lines.append(f'    "{rule_id}": frozenset({{')
        for pattern in patterns:
            lines.append(f"        {pattern!r},")
        lines.append("    }),")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="exit 1 when the committed file is out of date",
    )
    args = parser.parse_args(argv)

    text = render(collect())
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(ROOT)} is stale; rerun without --check")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0

    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
