"""Generate the documentation inventory: one row per page.

The inventory is a maintenance aid for information-architecture reviews.  It
records each page's path, title, declared description, audience and section,
so a rework can be planned from the repository rather than from a hand-kept
list that drifts.

Usage::

    python scripts/docs_inventory.py                 # print to stdout
    python scripts/docs_inventory.py --out docs-inventory.md
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

# The audience each top-level section serves.  A page inherits its section's
# audience; pages outside these sections are project records.
AUDIENCE = {
    "start-here": "New users",
    "workflows": "Users and operators",
    "security-design": "Security researchers, advanced users and auditors",
    "explanation": "Security researchers and advanced users",
    "rules": "Rule authors, security researchers and advanced users",
    "reference": "Developers, integrators and advanced users",
    "contributing": "Contributors and maintainers",
    "reports": "Researchers and operators",
    "": "All readers",
}


def _title(text: str) -> str:
    match = re.search(r"^#\s+(.+)$", text, re.M)
    return match.group(1).strip() if match else ""


def _description(text: str) -> str:
    match = re.search(r"^<!-- description:\s*(.*?)\s*-->", text, re.M)
    return match.group(1).strip() if match else ""


def rows() -> list[tuple[str, str, str, str]]:
    records = []
    for page in sorted(DOCS.rglob("*.md")):
        rel = page.relative_to(DOCS)
        section = rel.parts[0] if len(rel.parts) > 1 else ""
        audience = AUDIENCE.get(section, "All readers")
        text = page.read_text()
        records.append((rel.as_posix(), _title(text), _description(text), audience))
    return records


def table(records: list[tuple[str, str, str, str]]) -> str:
    lines = [
        "<!-- description: The documentation inventory, generated by "
        "scripts/docs_inventory.py. -->",
        "",
        "# Documentation Inventory",
        "",
        "One row per page: its path, declared title, declared description and",
        "audience. Regenerate with `python scripts/docs_inventory.py --out",
        "docs-inventory.md` after adding, moving or removing a page.",
        "",
        "| Path | Title | Description | Audience |",
        "|------|-------|-------------|----------|",
    ]
    for path, title, description, audience in records:
        safe = title.replace("|", "\\|")
        desc = description.replace("|", "\\|")
        lines.append(f"| `{path}` | {safe} | {desc} | {audience} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=None, help="write here instead of stdout")
    args = parser.parse_args(argv)
    body = table(rows())
    if args.out:
        Path(args.out).write_text(body)
        print(f"wrote {args.out} ({len(rows())} pages)")
    else:
        print(body, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
