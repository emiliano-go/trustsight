"""Package naming and source-repository divergence temporal emitters."""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

from ._temporal_common import _cluster, _host_of

if TYPE_CHECKING:
    from .temporal_engine import HistorySnapshot

# Hosts where an ecosystem package would be expected to live; a divergence
# from every one of these for a prefixed package is H053's signal.
_FORGE_HOSTS = frozenset({
    "github.com", "gitlab.com", "codeberg.org", "bitbucket.org",
    "sourceforge.net", "gitea.com", "gitea.io", "git.sr.ht",
})

_ECOSYSTEM_HOSTS = {
    "python": {"pypi.org", "pypi.io", "files.pythonhosted.org", "pypi.python.org"},
    "python2": {"pypi.org", "pypi.io", "files.pythonhosted.org", "pypi.python.org"},
    "python3": {"pypi.org", "pypi.io", "files.pythonhosted.org", "pypi.python.org"},
    "perl": {"cpan.org", "metacpan.org"},
    "ruby": {"rubygems.org"},
    "nodejs": {"npmjs.com", "registry.npmjs.org", "nodejs.org"},
    "node": {"npmjs.com", "registry.npmjs.org", "nodejs.org"},
    "php": {"packagist.org"},
    "lua": {"luarocks.org"},
    "rust": {"crates.io", "static.crates.io"},
    "haskell": {"hackage.haskell.org"},
    "ocaml": {"opam.ocaml.org"},
    "texlive": {"ctan.org"},
    "r": {"cran.r-project.org", "cloud.r-project.org"},
}


def _repo_path_tokens(url: str) -> set[str]:
    """Meaningful tokens from a source URL's path, minus version noise."""
    rest = url.split("://", 1)[-1]
    path = rest.split("/", 1)[1] if "/" in rest else ""
    tokens: set[str] = set()
    for part in path.split("/"):
        for piece in part.replace(".tar.gz", "").replace(".tgz", "").replace(
            ".tar", "").replace(".zip", "").replace(".git", "").split("."):
            # Lowercased to match ``_package_stem``: the overlap test below
            # compares a lowercased package name against these, so a repo
            # spelled ``GTAIV`` / ``Colloid-icon-theme`` never matched its
            # own package and H059 flagged it as divergent.
            piece = piece.rstrip("0123456789").lower()
            if len(piece) >= 3:
                tokens.add(piece)
    return tokens


def _repo_path_words(url: str) -> list[str]:
    """Ordered words from a source URL's path, for acronym matching."""
    rest = url.split("://", 1)[-1]
    path = rest.split("/", 1)[1] if "/" in rest else ""
    words: list[str] = []
    for piece in re.split(r"[/._-]+", path):
        # Split camelCase so `QualcommSoftwareCenter` is three words, not one.
        for word in re.findall(
                r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+", piece):
            word = word.lower()
            if len(word) >= 2:
                words.append(word)
    return words


def _is_acronym(token: str, words: list[str]) -> bool:
    """True when *token* is the initials of consecutive *words*."""
    token = token.lower()
    if not 2 <= len(token) <= 5:
        return False
    for start in range(len(words) - len(token) + 1):
        if all(words[start + i][0] == ch for i, ch in enumerate(token)):
            return True
    return False


def _ecosystem_prefix_of(name: str) -> str | None:
    """Ecosystem prefix (with a known canonical host) for *name*, or None."""
    lower = name.lower()
    for prefix in sorted(_ECOSYSTEM_HOSTS, key=len, reverse=True):
        if lower.startswith(prefix + "-"):
            return prefix
    return None


def _host_matches(host: str, canonical: set[str]) -> bool:
    """True when *host* is a canonical host or a subdomain of one.

    ``search.cpan.org`` is the same ecosystem as ``cpan.org``: an exact-host
    test made every CPAN module generated by an older tooling look divergent
    from the ecosystem it belongs to.
    """
    return any(host == item or host.endswith("." + item) for item in canonical)


def _name_host_divergence_findings(snapshot: HistorySnapshot) -> list[dict]:
    """H053 - name-token <-> host consensus divergence."""
    changes, source_repos = snapshot.changes, snapshot.source_repos
    out: list[dict] = []
    for name, status in changes.items():
        if status != "added":
            continue
        prefix = _ecosystem_prefix_of(name)
        if not prefix:
            continue
        repos = source_repos.get(name) or set()
        if not repos:
            continue
        hosts = {_host_of(r) for r in repos}
        canonical = _ECOSYSTEM_HOSTS[prefix]
        if any(_host_matches(host, canonical) for host in hosts):
            continue
        if hosts & _FORGE_HOSTS:
            continue
        out.append(_cluster(
            "H053",
            "Ecosystem/Host Divergence",
            f"{name} claims the {prefix} ecosystem but sources from "
            f"{', '.join(sorted(hosts)[:3])}",
            [name],
            severity="MEDIUM",
            category="naming",
            prefix=prefix,
            hosts=sorted(hosts),
        ))
    return out


def _name_repo_divergence_findings(snapshot: HistorySnapshot) -> list[dict]:
    """H059 - package name and source repo share no token."""
    from ..deps import _ecosystem_prefixes, _package_stem

    changes, source_repos = snapshot.changes, snapshot.source_repos
    prefixes = _ecosystem_prefixes()
    out: list[dict] = []
    for name, status in changes.items():
        if status != "added":
            continue
        repos = source_repos.get(name) or set()
        if not repos:
            continue
        # An unresolved expansion leaves a URL that names no real repository.
        # Tokenising it says "nothing in common", which is not evidence of
        # divergence: absence of a resolved repo is unknown, not a finding.
        if any("$" in repo or "{" in repo for repo in repos):
            continue
        stem_parts = _package_stem(name).split("-")
        tokens = {t for t in stem_parts if len(t) >= 3}
        if len(tokens) < 2:
            continue
        repo_tokens = set()
        for repo in repos:
            repo_tokens |= _repo_path_tokens(repo)
        if not repo_tokens:
            continue
        overlapping = any(
            t in rt or rt in t for t in tokens for rt in repo_tokens
        )
        if not overlapping:
            # A short leading token is often the vendor's acronym
            # (qsc = Qualcomm Software Center), which shares no literal
            # token with the URL but is the project's own name.
            lead = next(
                (t for t in stem_parts
                 if len(t) >= 3 and t not in prefixes), ""
            )
            if lead and any(
                    _is_acronym(lead, _repo_path_words(repo)) for repo in repos):
                overlapping = True
        if not overlapping:
            out.append(_cluster(
                "H059",
                "Name/Repo Divergence",
                f"{name} sources from {', '.join(sorted(repos)[:3])}, "
                "sharing no token with its name",
                [name],
                severity="MEDIUM",
                category="naming",
                repos=sorted(repos)[:3],
            ))
    return out
