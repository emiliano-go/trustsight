"""Fixed bounds for the isolated git sandbox (A14: source constants).

Every limit the git worker enforces is a literal here, not a function of the
input, so a hostile repository cannot choose how much memory, CPU or disk the
worker spends before the parent kills it.  The parent reads the same module
for the values it needs at the boundary (timeouts), so the two sides cannot
disagree.
"""

from __future__ import annotations

__all__ = [
    "GIT_WORKER_MEMORY_BYTES",
    "GIT_WORKER_CPU_SECONDS",
    "GIT_WORKER_RETIRE_CPU_SECONDS",
    "GIT_WORKER_FSIZE_BYTES",
    "GIT_WORKER_NOFILE",
    "GIT_WORKER_WRITE_BYTES",
    "GIT_WORKER_MAX_FILES",
    "GIT_WORKER_MONITOR_SECONDS",
    "GIT_WORKER_HOME_BYTES",
    "GIT_WORKER_HOME_FILES",
    "GIT_WORKER_ROOT_BYTES",
    "GIT_WORKER_ROOT_FILES",
    "GIT_PACK_MAX_OBJECTS",
    "GIT_PROXY_HEADER_BYTES",
    "GIT_PROXY_REQUEST_BODY_BYTES",
    "GIT_PROXY_TOTAL_REQUEST_BYTES",
    "GIT_PROXY_RESPONSE_BYTES",
    "GIT_PROXY_MAX_REQUESTS",
    "GIT_PROXY_DEADLINE_SECONDS",
    "GIT_PROXY_HEADER_SECONDS",
    "GIT_PROXY_BODY_SECONDS",
    "GIT_PROXY_ADVERT_BYTES",
    "GIT_PROXY_MAX_REFS",
    "GIT_PROXY_MAX_WANTS",
    "GIT_PROXY_MAX_HAVES",
    "GIT_PROXY_RESPONSE_HEADER_BYTES",
    "GIT_FETCH_TIMEOUT_SECONDS",
    "GIT_TRANSFER_DEADLINE_SECONDS",
    "GIT_OP_TIMEOUT_SECONDS",
    "MAX_TRANSFER_BYTES",
    "MAX_TOTAL_TRANSFER_BYTES",
]

#: Address-space ceiling for one git worker.  AUR repositories are recipe
#: sized; 1 GiB is far above any legitimate clone and far below the analysis
#: process, so a libgit2 allocation amplification exhausts the child.
GIT_WORKER_MEMORY_BYTES = 1024 * 1024 * 1024

#: Wall-CPU ceiling before the kernel kills the child.
GIT_WORKER_CPU_SECONDS = 60

#: Cumulative CPU after which the parent retires a worker, below the hard
#: ceiling, so the kill is attributed to the worker not to the next request.
GIT_WORKER_RETIRE_CPU_SECONDS = 45

#: Largest file the child may write.  It clones and writes the fetch marker,
#: so this cannot be 0 (unlike the tokenizer worker); it bounds the expanded
#: pack on disk to well above ``fetcher.MAX_TRANSFER_BYTES``.
GIT_WORKER_FSIZE_BYTES = 512 * 1024 * 1024

#: Descriptors the child may hold.  The fetch role inherits the proxy
#: socketpair pool as well as its stdio, and libgit2 opens several object
#: and pack files at once, so this is above the fetch path's working set.
GIT_WORKER_NOFILE = 256

#: Bytes the worker may write to storage before the parent kills it.  A
#: compromised worker can create files far beyond the network transfer cap;
#: ``/proc/<pid>/io`` gives the parent a trusted (kernel-accounted) ceiling.
GIT_WORKER_WRITE_BYTES = 512 * 1024 * 1024

#: Files/inodes the worker may create in its repository before the parent
#: kills it.  Per-file size limits do not bound a repository of empty files.
GIT_WORKER_MAX_FILES = 20_000

#: How often the parent checks the worker's write accounting.
GIT_WORKER_MONITOR_SECONDS = 0.25

#: Size and inode ceilings for the worker's private home tmpfs.
GIT_WORKER_HOME_BYTES = 64 * 1024 * 1024
GIT_WORKER_HOME_FILES = 4096

#: Size and inode ceilings for the mount-namespace root tmpfs.
GIT_WORKER_ROOT_BYTES = 32 * 1024 * 1024
GIT_WORKER_ROOT_FILES = 4096

#: Objects one pack may declare.  Bounds the object inventory the way
#: ``fetcher.MAX_HISTORY_COMMITS`` bounds the commit walk.
GIT_PACK_MAX_OBJECTS = 1_000_000

#: HTTP request header bytes the parent proxy accepts from a fetch worker.
#: The worker's request is generated by libgit2, not by the repository, but
#: a defect there must not make the parent buffer an unbounded header block.
GIT_PROXY_HEADER_BYTES = 32 * 1024

#: One worker-authored request body.  The parent drains it for HTTP
#: correctness but never forwards it; the ceiling bounds that drain.
GIT_PROXY_REQUEST_BODY_BYTES = 64 * 1024

#: Every synthesised upstream request body in one fetch session.  The worker's
#: body is not forwarded, so this is a bound on the parent-produced request.
GIT_PROXY_TOTAL_REQUEST_BYTES = 256 * 1024

#: Upload-pack response bytes the parent relays across one fetch session.
#: The parent counts this itself and charges it to the run budget, so a
#: compromised worker cannot under-report a transfer.  It matches the
#: per-transfer ceiling; HTTP headers are bounded separately.  A cumulative
#: cap keeps negotiation rounds from turning into repeated full packs.
GIT_PROXY_RESPONSE_BYTES = 256 * 1024 * 1024

#: Requests one proxy session may forward.  A full clone is GET info/refs
#: plus POST upload-pack.  An incremental fetch may need one POST per twenty
#: haves until the server acknowledges a common commit, plus a final POST with
#: done; libgit2 stops after 256 haves, so fifteen POSTs covers every round.
GIT_PROXY_MAX_REQUESTS = 16

#: Wall-clock ceiling for one proxy request and its response.
GIT_PROXY_DEADLINE_SECONDS = 180

#: Separate ceilings for the worker-authored request.  The response deadline
#: is for a pack transfer; it is far too long for a client that has not yet
#: finished sending its headers or body.
GIT_PROXY_HEADER_SECONDS = 15
GIT_PROXY_BODY_SECONDS = 30

#: Git refs advertisement the parent parses from the AUR.  AUR recipe
#: repositories advertise a handful of refs; the cap bounds a hostile reply
#: to a small memory and parse budget.
GIT_PROXY_ADVERT_BYTES = 256 * 1024
GIT_PROXY_MAX_REFS = 4096

#: Wants the parent will put into a synthesised upload-pack request.
GIT_PROXY_MAX_WANTS = 1024

#: Client ``have`` lines the parent will forward in one upload-pack request.
#: The request body cap already bounds this; the explicit cap keeps a
#: pathological negotiation from spending the whole body on haves.
GIT_PROXY_MAX_HAVES = 1024

#: HTTP response header block the parent validates before relaying.  The
#: body stays bounded by ``GIT_PROXY_RESPONSE_BYTES``.
GIT_PROXY_RESPONSE_HEADER_BYTES = 64 * 1024

#: Bytes one clone or fetch may pull.  The deadline bounds how *long* a
#: transfer runs, which on a fast link is not a bound on how much arrives:
#: 120 seconds is gigabytes, written straight to the cache directory.  An AUR
#: repository holds a recipe and occasionally a patch, so a few MiB is the
#: honest size and this is two orders of magnitude above it.  The child's
#: callback enforces it, and the parent proxy enforces the same ceiling on the
#: bytes it relays.
MAX_TRANSFER_BYTES = 256 * 1024 * 1024

#: Bytes every transfer in one analysis may pull between them.  The per-repo
#: cap alone is not a disk bound, because the dependency walk multiplies it by
#: ``depth.MAX_DEPTH_NODES`` (200).  The parent proxy counts the bytes it
#: actually relayed and the fetcher charges this run budget across packages.
MAX_TOTAL_TRANSFER_BYTES = 2 * 1024 * 1024 * 1024

#: Seconds libgit2 may spend on one transfer before the progress callback
#: aborts it.  A source constant rather than a literal in the worker, so the
#: bound is visible beside the byte ceilings it composes with.
GIT_TRANSFER_DEADLINE_SECONDS = 120

#: Wall-clock ceiling for the clone/fetch request, matching the transfer
#: deadline plus startup and index time.
GIT_FETCH_TIMEOUT_SECONDS = 180

#: Wall-clock ceiling for a local object/diff request.
GIT_OP_TIMEOUT_SECONDS = 60

#: Context lines a diff request may ask for.  The analysis uses 3; a caller
#: cannot make the worker build an arbitrarily wide patch.
GIT_DIFF_MAX_CONTEXT_LINES = 200

#: Tree entries one projection may inspect, and therefore files it may
#: return.  A recipe commits tens of files; a repository can commit millions
#: of tiny blobs, so the walk stops at the cap and reports incomplete rather
#: than building an unbounded list (the byte budget does not bound the entry
#: count).
GIT_TREE_MAX_ENTRIES = 100_000

#: Commit ids one ``commit_meta`` request may name.
GIT_COMMIT_META_MAX_OIDS = 64

#: Largest file body ``file_at`` will return (the two it serves are small).
GIT_FILE_AT_MAX_BYTES = 8 * 1024 * 1024
